"""Render original, editable chip event cues from assets/audio/events.json.

Python 3 and NumPy are the only dependencies. No external samples are used.
The existing office music and release jingle are not generated by this file.
"""
from pathlib import Path
import json
import math
import wave

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "audio"
PITCH_CLASSES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5,
                 "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def frequency(pitch):
    return 440 * 2 ** ((((int(pitch[-1]) + 1) * 12 + PITCH_CLASSES[pitch[:-1]]) - 69) / 12)


def blep(phase, step):
    """Soften pulse discontinuities without blurring the chip waveform."""
    result = np.zeros_like(phase)
    first = phase < step
    position = phase[first] / step[first]
    result[first] = position + position - position * position - 1
    last = phase > 1 - step
    position = (phase[last] - 1) / step[last]
    result[last] = position * position + position + position + 1
    return result


def clocked_noise(count, sample_rate, clock_hz, seed):
    steps = int(math.ceil(count * clock_hz / sample_rate)) + 1
    values = np.empty(steps)
    state = (seed & 0x7fff) or 1
    for index in range(steps):
        values[index] = 1 if state & 1 else -1
        feedback = (state ^ (state >> 1)) & 1
        state = (state >> 1) | (feedback << 14)
    indices = (np.arange(count) * clock_hz / sample_rate).astype(int)
    return values[indices]


def render_voice(voice, sample_rate, seed):
    seconds = voice["seconds"]
    count = round(seconds * sample_rate)
    time = np.arange(count) / sample_rate
    if voice["wave"] == "noise":
        signal = clocked_noise(count, sample_rate, voice["clock_hz"], seed)
        signal = signal * 0.7 + np.r_[signal[0], signal[:-1]] * 0.3
    else:
        start = frequency(voice["pitch"])
        finish = frequency(voice.get("end_pitch", voice["pitch"]))
        frequencies = start * (finish / start) ** (time / seconds)
        step = frequencies / sample_rate
        phase = np.cumsum(step) % 1
        if voice["wave"] == "triangle":
            signal = 1 - 4 * np.abs(phase - 0.5)
        else:
            duty = voice.get("duty", 0.25)
            signal = np.where(phase < duty, 1.0, -1.0)
            signal += blep(phase, step) - blep((phase - duty) % 1, step)
            signal = (signal - (2 * duty - 1)) / math.sqrt(4 * duty * (1 - duty))
    attack = np.minimum(time / 0.003, 1)
    release = np.minimum((count - 1 - np.arange(count)) / (sample_rate * 0.018), 1)
    envelope = np.clip(attack * release, 0, 1) * np.exp(-time * voice.get("decay", 2))
    return signal * envelope * voice["volume"]


def validate_manifest(manifest):
    assert manifest["sample_rate"] == 22050 and manifest["channels"] == 2
    for name, event in manifest["events"].items():
        assert 0.05 <= event["duration_seconds"] <= 2.4, name
        if "source" in event:
            assert name == "publish" and event["file"] == "release-jingle.wav"
            continue
        assert event["file"].startswith("event-") and event["file"].endswith(".wav"), name
        assert Path(event["file"]).name == event["file"], name
        assert 0.2 < event["peak"] < 0.65 and event["voices"], name
        for voice in event["voices"]:
            assert voice["wave"] in ("pulse", "triangle", "noise"), name
            assert voice["start"] >= 0 and voice["seconds"] > 0, name
            assert voice["start"] + voice["seconds"] <= event["duration_seconds"], name
            assert 0 < voice["volume"] <= 0.3, name
            if voice["wave"] != "noise":
                assert 60 < frequency(voice["pitch"]) < 1800, name
                assert 60 < frequency(voice.get("end_pitch", voice["pitch"])) < 1800, name
            if voice["wave"] == "pulse":
                assert voice.get("duty", 0.25) in (0.125, 0.25, 0.5), name


def render_event(event, manifest):
    sample_rate = manifest["sample_rate"]
    mix = np.zeros((round(event["duration_seconds"] * sample_rate), 2))
    for index, voice in enumerate(event["voices"]):
        sound = render_voice(voice, sample_rate, manifest["noise_seed"] + index * 101)
        start = round(voice["start"] * sample_rate)
        count = min(len(sound), len(mix) - start)
        pan = voice.get("pan", 0)
        mix[start:start + count, 0] += sound[:count] * (1 - pan * 0.25)
        mix[start:start + count, 1] += sound[:count] * (1 + pan * 0.25)
    # Remove residual DC while keeping exact silent endpoints for clean stops.
    taper = np.minimum(np.arange(len(mix)) / (sample_rate * 0.003), 1)
    taper *= np.minimum((len(mix) - 1 - np.arange(len(mix))) / (sample_rate * 0.012), 1)
    mix -= taper[:, None] * (mix.sum(axis=0) / taper.sum())
    peak = np.max(np.abs(mix))
    assert peak > 0 and np.isfinite(mix).all()
    mix *= event["peak"] / peak
    return np.round(mix * 32767).astype("<i2")


def main():
    manifest = json.loads((OUTPUT / "events.json").read_text(encoding="utf-8"))
    validate_manifest(manifest)
    generated = []
    for name, event in manifest["events"].items():
        if "source" in event:
            continue
        pcm = render_event(event, manifest)
        with wave.open(str(OUTPUT / event["file"]), "wb") as handle:
            handle.setnchannels(manifest["channels"])
            handle.setsampwidth(2)
            handle.setframerate(manifest["sample_rate"])
            handle.writeframes(pcm.tobytes())
        generated.append({"event": name, "file": event["file"], "seconds": len(pcm) / manifest["sample_rate"]})
    print(json.dumps({"generated": generated, "existing_jingle_unchanged": True}, indent=2))


if __name__ == "__main__":
    main()
